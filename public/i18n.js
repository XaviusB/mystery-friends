const STORAGE_KEY = 'mf-lang';
const supported = Object.keys(messages);

function detect() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (supported.includes(saved)) return saved;
  const nav = (navigator.languages || [navigator.language]).map((l) => (l || '').slice(0, 2).toLowerCase());
  return nav.find((l) => supported.includes(l)) || 'en';
}

export let lang = detect();
document.documentElement.lang = lang;
document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

export function t(key, params = {}) {
  const str = messages[lang][key] ?? messages.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

export function setLang(code) {
  localStorage.setItem(STORAGE_KEY, code);
  location.reload();
}

export const languages = supported.map((code) => ({ code, name: messages[code].name }));
